    public static String AutoGeneratedStudent() {
        int max = 0;
        for (User u : users) {
            String userID = u.getUserID();
            if (userID.startsWith("S")) {
                int number = Integer.parseInt(userID.substring(1));

                if (number > max) {
                    max = number;
                }
            }
        }
        return String.format("S%03d", max + 1);
    }

